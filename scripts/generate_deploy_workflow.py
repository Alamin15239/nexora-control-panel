#!/usr/bin/env python3
"""Generate apps/cloudflare-api/src/github-deploy-workflow.ts.

Keeps the deployed workflow constant byte-for-byte identical with
docs/templates/nexora-deploy.yml (v2), and embeds a frozen copy of the v1
template (npm-only builds) so ensureNexoraDeploymentWorkflow can recognize and
upgrade repositories that still carry the previous revision.
"""
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
template = (ROOT / "docs/templates/nexora-deploy.yml").read_text(encoding="utf-8")
v1 = subprocess.run(
    ["git", "-C", str(ROOT), "show", "HEAD:docs/templates/nexora-deploy.yml"],
    check=True, capture_output=True, text=True,
).stdout

assert "npm run build --if-present" in template, "template v2 must contain the conditional build"
assert 'test -f package.json\n          test -f package-lock.json' not in template, "template v2 must not hard-require npm files"
assert "npm ci" in v1, "frozen v1 must be the npm-only revision"

out = ROOT / "apps/cloudflare-api/src/github-deploy-workflow.ts"
header = (
    "// Canonical static deployment workflow installed by Nexora when a repository is linked.\n"
    "// Keep this byte-for-byte aligned with docs/templates/nexora-deploy.yml.\n"
    "// Generated by scripts/generate_deploy_workflow.py - do not edit by hand.\n"
    "export const NEXORA_DEPLOY_WORKFLOW = " + json.dumps(template) + ";\n\n"
    "// Frozen copy of the previous workflow revision (v1: npm-only static builds).\n"
    "// Repositories that still carry v1 are upgraded in place during linking;\n"
    "// v1 detection must stay byte-exact so customer-modified workflows are never\n"
    "// silently replaced.\n"
    "export const NEXORA_DEPLOY_WORKFLOW_V1 = " + json.dumps(v1) + ";\n"
)
out.write_text(header, encoding="utf-8")
print(f"wrote {out} ({len(template)} bytes v2, {len(v1)} bytes v1)")
